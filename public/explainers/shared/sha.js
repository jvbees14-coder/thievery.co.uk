// ---------------------------------------------------------------------------
// How it works: SHA-1, SHA-256 and HMAC, small and synchronous.
//
// The browser has these in crypto.subtle, but only as promises, and a scene
// that redraws as somebody types wants an answer in the same frame. These
// follow FIPS 180-4 and RFC 2104 line for line and are checked against
// their published test vectors ("abc" for both hashes, and RFC 6238's
// one-time codes). They are for showing how the thing works, on a few
// hundred bytes at a time; nothing on the site relies on them for safety.
// ---------------------------------------------------------------------------

/** A string as UTF-8 bytes. */
export const utf8 = (s) => new TextEncoder().encode(s);

/** Bytes as lower-case hexadecimal. */
export const hex = (bytes) => Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');

const rotl = (x, n) => (x << n) | (x >>> (32 - n));
const rotr = (x, n) => (x >>> n) | (x << (32 - n));

// Both hashes pad the message the same way: a 1 bit, zeros, and the length
// in bits as the last eight bytes of a 64-byte block.
function blocks(bytes) {
  const n = bytes.length;
  const total = Math.ceil((n + 9) / 64) * 64;
  const buf = new Uint8Array(total);
  buf.set(bytes);
  buf[n] = 0x80;
  const bits = n * 8;
  const view = new DataView(buf.buffer);
  view.setUint32(total - 8, Math.floor(bits / 0x100000000));
  view.setUint32(total - 4, bits >>> 0);
  return view;
}

function out(words) {
  const b = new Uint8Array(words.length * 4);
  const v = new DataView(b.buffer);
  words.forEach((w, i) => v.setUint32(i * 4, w >>> 0));
  return b;
}

export function sha1(bytes) {
  const view = blocks(bytes);
  let h = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476, 0xc3d2e1f0];
  const w = new Array(80);
  for (let off = 0; off < view.byteLength; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getUint32(off + i * 4);
    for (let i = 16; i < 80; i++) w[i] = rotl(w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16], 1);
    let [a, b, c, d, e] = h;
    for (let i = 0; i < 80; i++) {
      let f, k;
      if (i < 20) { f = (b & c) | (~b & d); k = 0x5a827999; }
      else if (i < 40) { f = b ^ c ^ d; k = 0x6ed9eba1; }
      else if (i < 60) { f = (b & c) | (b & d) | (c & d); k = 0x8f1bbcdc; }
      else { f = b ^ c ^ d; k = 0xca62c1d6; }
      const t = (rotl(a, 5) + f + e + k + w[i]) | 0;
      e = d; d = c; c = rotl(b, 30); b = a; a = t;
    }
    h = [h[0] + a, h[1] + b, h[2] + c, h[3] + d, h[4] + e].map((x) => x | 0);
  }
  return out(h);
}

